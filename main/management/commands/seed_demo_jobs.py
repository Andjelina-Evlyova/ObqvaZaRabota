class Command(BaseCommand):
    help = "Добавя примерни обяви за работа в евро без дубликати."

    def handle(self, *args, **options):
        created_count = 0
        for job_data in DEMO_JOBS:
            _, created = JobPosting.objects.get_or_create(
                title=job_data["title"],
                company_name=job_data["company_name"],
                defaults={
                    key: value
                    for key, value in job_data.items()
                    if key not in {"title", "company_name"}
                },
            )
            created_count += int(created)

        self.stdout.write(
            self.style.SUCCESS(
                f"Добавени са {created_count} демо обяви. "
                f"Общо примерни обяви: {len(DEMO_JOBS)}."
            )
        )
